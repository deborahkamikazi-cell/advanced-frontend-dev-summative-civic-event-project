import { enforcePageAccess } from "../../auth/auth-guard.js";
import { loadAdminShell } from "../_shared.js";
import { openConfirmModal, showSuccess } from "../../utils/notifications.js";
import { deleteNotification, listNotifications } from "../../services/notifications.service.js";
import { adminPageHeader, dataRow, escapeHtml, loadAdminData, runAdminAction, statusBadge, tableMarkup } from "./admin-ui.js";

async function renderNotifications() {
  const { data: items } = await listNotifications();
  const rows = items.map((item) => dataRow([
    statusBadge(escapeHtml(item.type), "amber"),
    escapeHtml(item.title),
    escapeHtml(item.message),
    escapeHtml(new Date(item.created_at).toLocaleString()),
    `<button class="delete-notification font-medium text-red-600" data-id="${escapeHtml(item.id)}">Delete</button>`
  ])).join("");
  $("#manage-notifications-list").html(`
    ${adminPageHeader("Notifications", "Broadcasts and notifications addressed to your account. The API does not expose a list of every user's private notifications.")}
    <p class="ce-card mb-4 p-4 text-sm text-slate-600">Notifications are generated by content actions. Manual creation and broadcasting are not exposed by the API.</p>
    ${tableMarkup(["Type", "Title", "Message", "Created", "Action"], rows)}
  `);
}

if (enforcePageAccess({ adminOnly: true })) {
  await loadAdminShell("../../../components", { activeAdminNav: "notifications" });
  await loadAdminData("#manage-notifications-list", renderNotifications);
}

$(document).on("click", ".delete-notification", (event) => {
  const button = event.currentTarget;
  openConfirmModal({
    title: "Delete notification?",
    message: "This permanently deletes the notification, including for other recipients of a broadcast.",
    confirmLabel: "Delete",
    onConfirm: () => runAdminAction(button, async () => {
      await deleteNotification($(button).attr("data-id"));
      showSuccess("Notification deleted.");
      await loadAdminData("#manage-notifications-list", renderNotifications);
    })
  });
});
